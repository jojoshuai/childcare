// GetWHOStandards handles GET /api/who-standards.
// Query params: gender=male|female, type=weight|height
func GetWHOStandards(c *gin.Context) {
	gender := c.Query("gender")
	mType := c.Query("type")

	if gender != "male" && gender != "female" {
		errorResponse(c, http.StatusBadRequest, "INVALID_GENDER", "gender 参数应为 male 或 female")
		return
	}
	if mType != "weight" && mType != "height" {
		errorResponse(c, http.StatusBadRequest, "INVALID_TYPE", "type 参数应为 weight 或 height")
		return
	}

	data := whoData[gender][mType]
	c.JSON(http.StatusOK, gin.H{"data": data})
}
